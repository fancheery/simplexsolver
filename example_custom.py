r"""用自己的数据调用求解器。

演示三件事：
1. 换一组完全不同的数字（3 个变量）
2. 从一段文字题目「翻译」出 c、A、b —— 这就是建模
3. 批量跑多组数据

运行：
    .\.venv\Scripts\activate
    python example_custom.py
"""

from simplex import solve_lp

# ============================================================
# 例 1：一道 3 个变量的新题（和 simplex.py 里的完全不同）
#
#   max  2*x1 + 3*x2 + 4*x3
#   s.t. x1 + x2 + x3 <= 10
#        2*x1 + x2     <= 8
#             x2 + 2*x3 <= 12
#        x1, x2, x3 >= 0
# ============================================================

print("=" * 60)
print("例 1：三个变量")
print("=" * 60)

c = [2, 3, 4]
A = [
    [1, 1, 1],
    [2, 1, 0],
    [0, 1, 2],
]
b = [10, 8, 12]

x, obj, status = solve_lp(c, A, b)

print(f"状态  : {status}")
print(f"最优解: x1={x[0]:.3f}, x2={x[1]:.3f}, x3={x[2]:.3f}")
print(f"最优值: {obj:.3f}")
print()
print("验算（左边应该 <= 右边）：")
for i, row in enumerate(A):
    lhs = sum(a * xi for a, xi in zip(row, x))
    flag = "OK" if lhs <= b[i] + 1e-6 else "超出约束！"
    print(f"  约束 {i + 1}: {lhs:7.3f} <= {b[i]:7.3f}   {flag}")

print()

# ============================================================
# 例 2：从文字题目到 c/A/b —— 建模
#
# 题目：
#   某工厂生产 A、B 两种产品。
#   - A 每件利润 40 元，B 每件利润 30 元
#   - 每件 A 用 2 小时机器、1 公斤原料
#   - 每件 B 用 1 小时机器、2 公斤原料
#   - 每周机器 100 小时，原料 80 公斤
#   问：A、B 各生产多少件，每周利润最大？
#
# 建模：
#   设 a = A 的产量，b = B 的产量
#   max  40a + 30b
#   s.t. 2a +  b <= 100     （机器工时）
#         a + 2b <= 80      （原料）
#         a, b >= 0
# ============================================================

print("=" * 60)
print("例 2：建模 —— 工厂排产")
print("=" * 60)

c_factory = [40, 30]                    # 每件的利润
A_factory = [
    [2, 1],                             # 每件消耗的机器工时
    [1, 2],                             # 每件消耗的原料
]
b_factory = [100, 80]                   # 每周可用资源

a, profit, status = solve_lp(c_factory, A_factory, b_factory)

print(f"状态    : {status}")
print(f"最优排产: A 生产 {a[0]:.0f} 件，B 生产 {a[1]:.0f} 件")
print(f"每周利润: {profit:.0f} 元")
print()
print("资源占用：")
print(f"  机器: {2 * a[0] + 1 * a[1]:.0f} / 100 小时")
print(f"  原料: {1 * a[0] + 2 * a[1]:.0f} / 80 公斤")
print()
print("注意：机器工时正好用满 —— 说明机器是「瓶颈资源」，扩产该先加机器。")

print()

# ============================================================
# 例 3：批量跑多组数据
# ============================================================

print("=" * 60)
print("例 3：批量跑 3 组数据")
print("=" * 60)

problems = [
    ("小规模", [3, 5], [[3, 2], [1, 0], [0, 1]], [18, 4, 6]),
    ("三变量", [2, 3, 4], [[1, 1, 1], [2, 1, 0], [0, 1, 2]], [10, 8, 12]),
    ("单变量", [7], [[1]], [9]),
]

for name, c_i, A_i, b_i in problems:
    xi, obji, stati = solve_lp(c_i, A_i, b_i)
    sol = [round(float(v), 3) for v in xi]
    print(f"{name:6s} 状态={stati:9s} 最优值={obji:8.3f}  解={sol}")

print()
print("同一个函数，换三组数据，得到三个不同答案。")
print("函数不认识「示例」，它只认 c、A、b。")
